class Translator:
    """轻量文案翻译器，支持带命名参数的模板。"""

    def __init__(self, language: str = "zh") -> None:
        self.language = language if language in TRANSLATIONS else "zh"

    def t(self, key: str, **kwargs: Any) -> str:
        text = TRANSLATIONS.get(self.language, {}).get(key)
        if text is None:
            text = TRANSLATIONS["zh"].get(key, key)
        if kwargs:
            try:
                return text.format(**kwargs)
            except (KeyError, IndexError, ValueError):
                return text
        return text


def web_text(language: str) -> Dict[str, str]:
    return WEB_TRANSLATIONS.get(language, WEB_TRANSLATIONS["zh"])
